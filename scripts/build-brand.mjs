// Builds every brand output from brand/tokens.json: app/tokens.css, the logo SVGs in
// public/brand, the app icons and favicon. Run with `npm run brand` after editing the tokens.
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import opentype from 'opentype.js'
import sharp from 'sharp'

const root = path.resolve(import.meta.dirname, '..')
const tokens = JSON.parse(await readFile(path.join(root, 'brand/tokens.json'), 'utf8'))
const { color, symbol, product } = tokens

const banner = 'Generated by scripts/build-brand.mjs from brand/tokens.json. Do not edit by hand.'

// ---------------------------------------------------------------------------------------------
// CSS custom properties

function photoFilter(treatment) {
    return Object.entries(treatment).map(([name, value]) => `${name}(${value})`).join(' ')
}

function cssTokens() {
    const groups = [
        ['Color', Object.entries(color).map(([name, value]) => [name, value])],
        ['Aliases', [['surface-card', 'var(--surface)'], ['ink', 'var(--paper)']]],
        ['Product accents', Object.entries(product).map(([slug, { color: accent }]) => [`product-${slug}`, `var(--${accent})`])],
        // --font-sans and --font-editorial are set by next/font in app/layout.tsx.
        ['Font families', [['font-mono', tokens.font.mono]]],
        ['Font weights', Object.entries(tokens.weight).map(([name, value]) => [`weight-${name}`, value])],
        ['Type scale', Object.entries(tokens.text).map(([name, value]) => [`text-${name}`, value])],
        ['Line height', Object.entries(tokens.leading).map(([name, value]) => [`leading-${name}`, value])],
        ['Letter spacing', Object.entries(tokens.tracking).map(([name, value]) => [`tracking-${name}`, value])],
        ['Spacing', Object.entries(tokens.space).map(([name, value]) => [`space-${name}`, value])],
        ['Sizes', Object.entries(tokens.size).map(([name, value]) => [name, value])],
        ['Radius', Object.entries(tokens.radius).map(([name, value]) => [`radius-${name}`, value])],
        ['Borders', Object.entries(tokens.border).map(([name, value]) => [`border-${name}`, value])],
        ['Shadow', Object.entries(tokens.shadow).map(([name, value]) => [`shadow-${name}`, value])],
        ['Motion', [
            ...Object.entries(tokens.duration).map(([name, value]) => [`duration-${name}`, value]),
            ...Object.entries(tokens.ease).map(([name, value]) => [`ease-${name}`, value]),
            ...Object.entries(tokens.lift).map(([name, value]) => [`lift-${name}`, value]),
        ]],
        ['Photography', [
            ...Object.entries(tokens.photo).map(([name, value]) => [`photo-${name}`, photoFilter(value)]),
            ...Object.entries(tokens.veil).map(([name, value]) => [`veil-${name}`, value]),
        ]],
    ]

    const body = groups
        .map(([title, entries]) => `  /* ${title} */\n${entries.map(([name, value]) => `  --${name}: ${value};`).join('\n')}`)
        .join('\n\n')

    return `/* ${banner} */\n\n:root {\n${body}\n}\n`
}

// ---------------------------------------------------------------------------------------------
// Symbol, wordmark and lockups

const fonts = {
    bold: opentype.loadSync(path.join(root, 'assets/fonts/Manrope-Bold.ttf')),
    medium: opentype.loadSync(path.join(root, 'assets/fonts/Manrope-Medium.ttf')),
}

const round = (value) => Math.round(value * 100) / 100
const capHeight = (font, size) => (font.tables.os2.sCapHeight / font.unitsPerEm) * size

// Ticket and rail fills for each rendition of the symbol.
const inks = {
    color: { rail: color.paper, tickets: symbol.tickets.map((t) => color[product[t.product].color]) },
    'color-light': { rail: color['on-accent'], tickets: symbol.tickets.map((t) => color[product[t.product].color]) },
    paper: { rail: color.paper, tickets: symbol.tickets.map(() => color.paper) },
    ink: { rail: color['on-accent'], tickets: symbol.tickets.map(() => color['on-accent']) },
    current: { rail: 'currentColor', tickets: symbol.tickets.map(() => 'currentColor') },
}

// Wordmark ink per rendition: paper on dark grounds, on-accent on light or accent grounds.
const wordInk = { color: color.paper, 'color-light': color['on-accent'], paper: color.paper, ink: color['on-accent'], current: 'currentColor' }

function symbolRects(fills, x = 0, y = 0, scale = 1) {
    const rect = ({ x: rx, y: ry, width, height }, fill) =>
        `<rect x="${round(x + rx * scale)}" y="${round(y + ry * scale)}" width="${round(width * scale)}" height="${round(height * scale)}" fill="${fill}"/>`
    return [rect(symbol.rail, fills.rail), ...symbol.tickets.map((ticket, i) => rect(ticket, fills.tickets[i]))].join('')
}

// Sets a line of text as outlined paths with tracking (em), baseline at y.
function textPath(text, font, size, tracking, x, baseline) {
    const glyphs = font.stringToGlyphs(text)
    const scale = size / font.unitsPerEm
    let cursor = x
    let d = ''
    let bottom = baseline
    glyphs.forEach((glyph, index) => {
        const glyphPath = glyph.getPath(cursor, baseline, size)
        d += glyphPath.toPathData(2)
        bottom = Math.max(bottom, glyphPath.getBoundingBox().y2)
        cursor += glyph.advanceWidth * scale
        if (index < glyphs.length - 1) {
            cursor += font.getKerningValue(glyph, glyphs[index + 1]) * scale + tracking * size
        }
    })
    return { d, width: cursor - x, bottom }
}

function svg(width, height, content, title) {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${round(width)} ${round(height)}" width="${round(width)}" height="${round(height)}" role="img" aria-label="${title}"><title>${title}</title>${content}</svg>\n`
}

const wordmarkTracking = parseFloat(tokens.tracking.wordmark)

function wordmark(variant) {
    const size = 100
    const cap = capHeight(fonts.bold, size)
    const { d, width } = textPath('SEBICHE', fonts.bold, size, wordmarkTracking, 0, cap)
    return svg(width, cap, `<path fill="${wordInk[variant]}" d="${d}"/>`, 'SEBICHE')
}

// Horizontal lockup, as in the site header: the symbol box is 2.3× the wordmark size and sits one
// ticket width (18% of the symbol) from it. Cropped to the artwork.
function lockupHorizontal(variant) {
    const symbolBox = 100
    const size = symbolBox / 2.3
    const cap = capHeight(fonts.bold, size)
    const left = symbol.rail.x
    const top = symbol.rail.y
    const bottom = Math.max(...symbol.tickets.map((t) => t.y + t.height))
    const textX = symbolBox - left + symbol.clearSpace * symbolBox - left
    const baseline = symbolBox / 2 + cap / 2 - top
    const { d, width } = textPath('SEBICHE', fonts.bold, size, wordmarkTracking, textX, baseline)
    const content = symbolRects(inks[variant], -left, -top) + `<path fill="${wordInk[variant]}" d="${d}"/>`
    return svg(textX + width, bottom - top, content, 'SEBICHE')
}

// Stacked lockup for square formats: the wordmark spans the rail; one ticket width below the symbol.
function lockupStacked(variant) {
    const railWidth = symbol.rail.width
    const probe = textPath('SEBICHE', fonts.bold, 100, wordmarkTracking, 0, 0).width
    const size = (100 * railWidth * 1.5) / probe
    const cap = capHeight(fonts.bold, size)
    const width = railWidth * 1.5
    const symbolX = (width - symbol.viewBox) / 2
    const top = symbol.rail.y
    const bottom = Math.max(...symbol.tickets.map((t) => t.y + t.height))
    const baseline = bottom - top + symbol.clearSpace * symbol.viewBox + cap
    const { d } = textPath('SEBICHE', fonts.bold, size, wordmarkTracking, 0, baseline)
    const content = symbolRects(inks[variant], symbolX, -top) + `<path fill="${wordInk[variant]}" d="${d}"/>`
    return svg(width, baseline, content, 'SEBICHE')
}

// Product endorsement: product name in its color, then "by SEBICHE", on one baseline.
function endorsement(slug, variant) {
    const { name, color: accent } = product[slug]
    const size = 100
    const small = size * 0.4
    const gap = small * 0.5
    const ascent = capHeight(fonts.medium, size)
    const nameText = textPath(name, fonts.medium, size, parseFloat(tokens.tracking.product), 0, ascent)
    const byX = nameText.width + gap * 1.5
    const byText = textPath('by', fonts.medium, small, 0, byX, ascent)
    const markX = byX + byText.width + gap
    const markText = textPath('SEBICHE', fonts.bold, small, wordmarkTracking, markX, ascent)
    const fills = variant === 'ink'
        ? { name: color['on-accent'], by: color['on-accent'], mark: color['on-accent'] }
        : { name: color[accent], by: color.muted, mark: color.paper }
    const height = Math.max(nameText.bottom, byText.bottom, markText.bottom)
    const content = `<path fill="${fills.name}" d="${nameText.d}"/><path fill="${fills.by}" d="${byText.d}"/><path fill="${fills.mark}" d="${markText.d}"/>`
    return svg(markX + markText.width, height, content, `${name} by SEBICHE`)
}

function symbolFile(variant) {
    return svg(symbol.viewBox, symbol.viewBox, symbolRects(inks[variant]), 'SEBICHE')
}

// ---------------------------------------------------------------------------------------------
// App icons

function iconSvg(scale = 1) {
    const offset = (symbol.viewBox - symbol.viewBox * scale) / 2
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100"><rect width="100" height="100" fill="${color.ground}"/>${symbolRects(inks.color, offset, offset, scale)}</svg>\n`
}

function png(source, size) {
    return sharp(Buffer.from(source), { density: 72 * (size / 100) * 4 })
        .resize(size, size, { kernel: 'lanczos3' })
        .png()
        .toBuffer()
}

// Pixel-snapped 16px one-ink symbol: below 24px the brand asks for one ink, and the
// 100-unit geometry blurs at this size.
function favicon16() {
    const source = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges"><rect width="16" height="16" fill="${color.ground}"/><rect x="1" y="3" width="13" height="2" fill="${color.paper}"/><rect x="2" y="6" width="3" height="5" fill="${color.paper}"/><rect x="6" y="6" width="3" height="7" fill="${color.paper}"/><rect x="10" y="6" width="3" height="4" fill="${color.paper}"/></svg>`
    return sharp(Buffer.from(source), { density: 72 }).png().toBuffer()
}

// ICO container with embedded PNG frames.
function ico(frames) {
    const header = Buffer.alloc(6 + 16 * frames.length)
    header.writeUInt16LE(0, 0)
    header.writeUInt16LE(1, 2)
    header.writeUInt16LE(frames.length, 4)
    let offset = header.length
    frames.forEach(({ size, data }, index) => {
        const entry = 6 + 16 * index
        header.writeUInt8(size, entry)
        header.writeUInt8(size, entry + 1)
        header.writeUInt16LE(1, entry + 4)
        header.writeUInt16LE(32, entry + 6)
        header.writeUInt32LE(data.length, entry + 8)
        header.writeUInt32LE(offset, entry + 12)
        offset += data.length
    })
    return Buffer.concat([header, ...frames.map((frame) => frame.data)])
}

// ---------------------------------------------------------------------------------------------

const outputs = {
    'app/tokens.css': cssTokens(),
    'app/icon.svg': iconSvg(),
}

for (const variant of ['color', 'color-light', 'paper', 'ink', 'current']) {
    outputs[`public/brand/sebiche-pase-${variant}.svg`] = symbolFile(variant)
}
for (const variant of ['paper', 'ink', 'current']) {
    outputs[`public/brand/sebiche-wordmark-${variant}.svg`] = wordmark(variant)
}
for (const variant of ['color', 'color-light', 'paper', 'ink']) {
    outputs[`public/brand/sebiche-lockup-${variant}.svg`] = lockupHorizontal(variant)
    outputs[`public/brand/sebiche-lockup-stacked-${variant}.svg`] = lockupStacked(variant)
}
for (const slug of Object.keys(product)) {
    outputs[`public/brand/${slug}-by-sebiche.svg`] = endorsement(slug, 'color')
    outputs[`public/brand/${slug}-by-sebiche-ink.svg`] = endorsement(slug, 'ink')
}


const icon = iconSvg()
const binaries = {
    'public/brand/icon-192.png': await png(icon, 192),
    'public/brand/icon-512.png': await png(icon, 512),
    'public/brand/icon-maskable-512.png': await png(iconSvg(0.72), 512),
    'app/apple-icon.png': await png(icon, 180),
    'app/favicon.ico': ico([
        { size: 16, data: await favicon16() },
        { size: 32, data: await png(icon, 32) },
        { size: 48, data: await png(icon, 48) },
    ]),
}

const files = { ...outputs, ...binaries }

// --check: fail when a generated file no longer matches brand/tokens.json (for CI).
if (process.argv.includes('--check')) {
    const stale = []
    for (const [file, content] of Object.entries(files)) {
        const current = await readFile(path.join(root, file)).catch(() => null)
        if (!current || !current.equals(Buffer.from(content))) stale.push(file)
    }
    if (stale.length) {
        console.error(`Brand: out of date, run \`npm run brand\`:\n  ${stale.join('\n  ')}`)
        process.exit(1)
    }
    console.log(`Brand: ${Object.keys(files).length} files match brand/tokens.json`)
} else {
    for (const [file, content] of Object.entries(files)) {
        await writeFile(path.join(root, file), content)
    }
    console.log(`Brand: wrote ${Object.keys(files).length} files from brand/tokens.json`)
}
